    //Check if it require to popup warning before finalising inactive safe having counted amount to move
    boolean isSafeFinalisingWarningRequired(SafeSession safeSession){
        Safe safe = safeService.getSafeById(safeSession.safeId)
        boolean hasTender = safeSession.getCombinedReconciledAndPendingTotals().stream()
                .anyMatch { it.getValue() != BigDecimal.ZERO }
        return !safe.active && hasTender
    }

    private SafeSession populateNewSafeSession(int retailerId, int storeId, int safeId, boolean isAutoGenerated) throws Exception {
        int sessionNumber = getLastSessionNumber(retailerId, storeId, safeId) + 1
        FinancialWeek financialWeek = financialWeekService.getFinancialWeek(retailerId)
        User loggedInUser = loadLoggedInUser()
        SafeSession safeSession = new SafeSession(retailerId, storeId, safeId)
        safeSession.setSessionNumber(sessionNumber)
        safeSession.setSessionStatus(SafeSessionStatus.OPEN)
        safeSession.setOpenUserId(loggedInUser.getId())
        safeSession.setOpenUsername(loggedInUser.getUsername())
        safeSession.setOpenTime(commonService.convertDateTimeToString(new DateTime()))
        if (financialWeek != null){
            safeSession.setFinancialWeek(financialWeek)
        }
        saveSafeSession(safeSession) // Save session
        addAudit(safeSession, SafeSessionAction.OPEN, isAutoGenerated, loggedInUser, null) // Audit for session open action
        return safeSession;
    }

    void addAudit(SafeSession safeSession, SafeSessionAction safeSessionAction, boolean isAutoGenerated, User loggedInUser, Integer tenderMovementId){
        try {
            SafeSessionAudit safeSessionAudit = initializeSafeSessionAudit(safeSession, safeSessionAction, isAutoGenerated, loggedInUser, tenderMovementId)
            saveSafeSessionAudit(safeSessionAudit)
        } catch (Exception ex) {
            log.error("Error adding audit for session id: ${safeSession.getId()}, error ${ex.getMessage()} ", ex)
        }
    }

    private SafeSessionAudit initializeSafeSessionAudit(SafeSession safeSession, SafeSessionAction safeSessionAction, boolean isAutoGenerated, User loggedInUser, Integer tenderId) {
        SafeSessionAudit safeSessionAudit = new SafeSessionAudit()
        safeSessionAudit.with {
            sessionId = safeSession.id
            autoGenerated = isAutoGenerated
            action = safeSessionAction
            userId = loggedInUser?.id
            username = loggedInUser?.username
            timestamp = new DateTime()
            tenderMovementId = tenderId
        }

        if (safeSessionAction in [SafeSessionAction.SPOT_CHECK, SafeSessionAction.RECONCILE, SafeSessionAction.RECOUNT, SafeSessionAction.FINALISE, SafeSessionAction.CASH_LIFT,
                                  SafeSessionAction.PAID_IN, SafeSessionAction.ADD_FLOAT, SafeSessionAction.BANK_DEPOSIT, SafeSessionAction.BANK_RECEIPT]) {
            JsonObject jsonObject = new JsonObject()

            addJsonFieldToObject(jsonObject, "tenderTotals", safeSession.tenderTotals)
            addJsonFieldToObject(jsonObject, "pendingTenderTotals", safeSession.pendingTenderTotals)

            if (safeSessionAction in [SafeSessionAction.RECONCILE, SafeSessionAction.RECOUNT, SafeSessionAction.FINALISE]) {
                addJsonFieldToObject(jsonObject, "reconciliationTotals", safeSession.reconciliationTotals)
            }

            safeSessionAudit.extras = jsonObject
        }

        return safeSessionAudit
    }

    private void addJsonFieldToObject(JsonObject jsonObject, String key, def value) {
        if (value != null) {
            try {
                String jsonString = gsonProvider?.gson?.toJson(value) ?: "{}"
                JsonElement jsonElement = JsonParser.parseString(jsonString)

                if (jsonElement.isJsonArray()) {
                    jsonObject.add(key, jsonElement.getAsJsonArray())
                } else if (jsonElement.isJsonObject()) {
                    jsonObject.add(key, jsonElement.getAsJsonObject())
                } else {
                    jsonObject.add(key, jsonElement)
                }
            } catch (Exception ex) {
                log.error("Error parsing extra for audit for key: $key : ${ex.message}", ex)
                jsonObject.add(key, new JsonArray())
            }
        } else {
            jsonObject.add(key, JsonNull.INSTANCE)
        }
    }

    private User loadLoggedInUser(){
        int id = springSecurityService.principal.id
        User loggedInUser = userService.getUser(id)
        return loggedInUser
    }

    private Integer getLastSessionNumber(int retailerId, int storeId, int safeId) {
        int result = 0;
        try (Connection conn = getConnection(); CallableStatement getSessionNumberStmt = conn.prepareCall("{ call getPreviousSessionNumberForSafe(?, ?, ?) }")) {
            getSessionNumberStmt.setInt(1, retailerId)
            getSessionNumberStmt.setInt(2, storeId)
            getSessionNumberStmt.setInt(3, safeId)

            try (ResultSet rs = getSessionNumberStmt.executeQuery()) {
                if (rs.next()) {
                    result = rs.getInt("sessionNumber")
                }
            }
        } catch (SQLException ex) {
            log.error("Sql error loading last safe session number for from retailer: ${retailerId} store: ${storeId} safeId: ${safeId} error: ${ex.getMessage()}", ex);
            throw new RuntimeException("Sql error loading last safe session number for from retailer: ${retailerId} store: ${storeId} tillId: ${safeId} error: ${ex.getMessage()}", ex);
        } catch (Exception ex) {
            log.error("Unexpected error loading last safe session number for from retailer: ${retailerId} store: ${storeId} safeId: ${safeId} error: ${ex.getMessage()}", ex);
            throw new RuntimeException("Unexpected error loading last safe session number for from retailer: ${retailerId} store: ${storeId} safeId: ${safeId} error: ${ex.getMessage()}", ex);
        }
        return result;
    }


    private void saveSafeSessionAudit(SafeSessionAudit safeSessionAudit){
        try (Connection conn = getConnection(); CallableStatement saveSafeSessionStatement = conn.prepareCall("{ call saveSafeSessionAudit(?, ?, ?, ?, ?, ?, ?, ?, ?) }")) {
            if (safeSessionAudit.getId() > 0) {
                saveSafeSessionStatement.setInt(1, safeSessionAudit.getId())
            } else {
                saveSafeSessionStatement.setNull(1, Types.INTEGER)
            }
            saveSafeSessionStatement.setInt(2, safeSessionAudit.getSessionId())
            saveSafeSessionStatement.setBoolean(3, safeSessionAudit.isAutoGenerated())
            saveSafeSessionStatement.setString(4, safeSessionAudit.getAction().toString())
            saveSafeSessionStatement.setInt(5, safeSessionAudit.getUserId())
            saveSafeSessionStatement.setString(6, safeSessionAudit.getUsername())
            saveSafeSessionStatement.setTimestamp(7, commonService.convertToSqlTimestamp(safeSessionAudit.getTimestamp()))
            saveSafeSessionStatement.setString(8, (safeSessionAudit?.extras != null) ? gsonProvider.gson.toJson(safeSessionAudit.extras) : null)
            if (safeSessionAudit.getTenderMovementId()) {
                saveSafeSessionStatement.setInt(9, safeSessionAudit.getTenderMovementId())
            } else {
                saveSafeSessionStatement.setNull(9, Types.INTEGER)
            }
            saveSafeSessionStatement.executeUpdate();
        } catch (SQLException ex) {
            log.error("Sql error saving safe session audit for safe session id: ${safeSessionAudit.getSessionId()} error: ${ex.getMessage()}", ex)
            throw new RuntimeException("Sql error saving safe session audit for safe session id: ${safeSessionAudit.getSessionId()} error: ${ex.getMessage()}", ex)
        } catch (Exception ex) {
            log.error("Unexpected error saving safe session audit for safe session id: ${safeSessionAudit.getSessionId()} error: ${ex.getMessage()}", ex)
            throw new RuntimeException("Unexpected error saving safe session audit for safe session id: ${safeSessionAudit.getSessionId()} error: ${ex.getMessage()}", ex)
        }
    }

    private void updateSafeSessionSaveFields(SafeSessionSaveCommand safeSessionSaveCommand, SafeSession safeSession, User loggedInUser) {
        if (safeSession.sessionStatus == SafeSessionStatus.OPEN || safeSession.sessionStatus == SafeSessionStatus.RECONCILED) {
            if (!safeSessionSaveCommand.isFinalise) {
                // If the request is not a final request (Intermediate --> reconcile or recount)
                // Then should move on pending reconciliation totals into actual reconciliation totals
                // And update variance reason and reason text
                safeSession.setReconciliationTotals(safeSession.getPendingReconciliationTotals())
                safeSession.setPendingReconciliationTotals(new ArrayList<ReconciliationTotal>())
                // And if the version hasn't changed then pending totals would have been counted
                safeSession.transferPendingTotals()

                if (safeSessionSaveCommand.tenderReconciliationVarianceReason != null) { // Update variance and variance text
                    safeSession.reconciliationTotals.findAll { it.variance != BigDecimal.ZERO }?.each {
                        it.varianceReason = safeSessionSaveCommand.tenderReconciliationVarianceReason
                        it.varianceReasonText = safeSessionSaveCommand.tenderReconciliationVarianceReasonText
                    }
                }

                if (!safeSessionSaveCommand.isRecount) {
                    safeSession.reconciledDate = DateTime.now()
                    safeSession.reconciledByUserId = loggedInUser.getId()
                    safeSession.reconciledByUsersName = loggedInUser.getUsername()
                    safeSession.sessionStatus = SafeSessionStatus.RECONCILED
                } else {
                    safeSession.reReconciledDate = DateTime.now()
                    safeSession.reReconciledByUserId = loggedInUser.getId()
                    safeSession.reReconciledByUsersName = loggedInUser.getUsername()
                    safeSession.totalRecountAttempts = (safeSession.totalRecountAttempts ?: 0) + 1
                }
            } else {
                safeSession.sessionStatus = SafeSessionStatus.FINALISED
                safeSession.finalisedTime = commonService.convertDateTimeToString(DateTime.now())
                safeSession.finalisedUserId = loggedInUser.getId()
                safeSession.finalisedUsername = loggedInUser.getUsername()
            }
        }
    }

    private BigDecimal calculateCashTotal(SafeSessionCashUpCommand safeSessionCashUpCommand) {
        switch(safeSessionCashUpCommand.cashUpBy) {
            case "VALUE":
                return sumDenominations(safeSessionCashUpCommand)
            case "DENOMINATION":
                return sumDenominationsWithMultipliers(safeSessionCashUpCommand)
            default:
                return safeSessionCashUpCommand.cashTotal
        }
    }

    private static BigDecimal sumDenominations(SafeSessionCashUpCommand cmd) {
        ([cmd.fiftyPounds, cmd.twentyPounds, cmd.tenPounds, cmd.fivePounds, cmd.twoPounds, cmd.onePounds, cmd.fiftyPences, cmd.twentyPences, cmd.tenPences,
          cmd.fivePences, cmd.twoPences, cmd.onePences].sum() ?: 0) as BigDecimal
    }

    private static BigDecimal sumDenominationsWithMultipliers(SafeSessionCashUpCommand cmd) {
        ([cmd.fiftyPounds * 50, cmd.twentyPounds * 20, cmd.tenPounds * 10, cmd.fivePounds * 5, cmd.twoPounds * 2, cmd.onePounds, cmd.fiftyPences * 0.50, cmd.twentyPences * 0.20,
          cmd.tenPences * 0.10, cmd.fivePences * 0.05, cmd.twoPences * 0.02, cmd.onePences * 0.01].sum() ?: 0) as BigDecimal
    }
