    boolean hasActiveSafeSession(Integer safeId) {
        return !getActiveSafeSessions(safeId).isEmpty()
    }

    def createNewSafeSession(int retailerId, int storeId, int safeId, boolean isAutoGenerated) {
        if (!hasActiveSafeSession(safeId)) {
            populateNewSafeSession(retailerId, storeId, safeId, isAutoGenerated)
        }
    }

    SafeSession createNewSafeSessionWithTenderTotals(int retailerId, int storeId, int safeId, List<TenderTotal> tenderTotals, boolean isAutoGenerated) {
        if (!hasActiveSafeSession(safeId)) {
            populateNewSafeSession(retailerId, storeId, safeId, isAutoGenerated)
        }

        if (tenderTotals) {
            List<ReconciliationTotal> addedTenderAmounts = new ArrayList<>()

            tenderTotals?.each { tenderTotal ->
                if (tenderTotal.tenderTypeId && tenderTotal.value != BigDecimal.ZERO) {
                    def reconciliationTotal = new ReconciliationTotal(tenderTotal.tenderTypeId, tenderTotal.tenderTypeName, tenderTotal.cashTender)
                    reconciliationTotal.value = tenderTotal.value

                    addedTenderAmounts.add(reconciliationTotal)
                }
            }

//            for (tender in tenderTotals) {
//                def value = tender.value
//                if (tender.tenderType != null && value != null && value != BigDecimal.ZERO) {
//                    addedTenderAmounts.put(tender.tenderType, value)
//                }
//            }

            // this is resetting the counts, does that matter?
            SafeSession updatedSession = addTenderToSafe(safeId, addedTenderAmounts)

            if (updatedSession != null) {
                return updatedSession
            }
        }

        // shouldn't get here if the update was successful
        throw new SafeSessionUpdateException(null, "Failed to add tender to the new Safe Session")
    }

    SafeSession addTenderToSafe(int safeId, List<ReconciliationTotal> tenderAmounts) {
        if (tenderAmounts == null || tenderAmounts.isEmpty()) {
            return getActiveSession(safeId)
        }

        try (Connection conn = getConnection()) {
            int attempt = 0
            while (attempt < 10) {
                attempt++
                SafeSession session = getActiveSessionUsingConnection(conn, safeId)

                if (session) {
                    for (amount in tenderAmounts) {
                        if (safeSession.getSessionStatus() != SafeSessionStatus.OPEN) {
                            safeSession.addToPendingTotals(amount.tenderTypeId, amount.tenderTypeName, amount.cashTender, amount.value)
                        } else {
                            safeSession.addToTotals(amount.tenderTypeId, amount.tenderTypeName, amount.cashTender, amount.value)
                        }
                    }

                    int sessionId = saveSafeSessionUsingConnection(conn, safeSession)

                    if (sessionId > 0) {
                        return getSafeSessionUsingConnection(conn, sessionId) // refresh the versionId
                    }
                } else {
                    // if there is no active sessions then it might be finalising so give it half a second
                    sleep(500)
                }
            }
        }
        String errorMsg = "Failed to add tender movements for retailer: ${springSecurityService.principal.retailerId}," +
                " store: ${springSecurityService.principal.storeId} and safeId: ${safeId}"
        log.error(errorMsg)
        throw new RuntimeException(errorMsg)
    }

    def saveSafeSession(SafeSession safeSession) throws SafeSessionUpdateException {
        try (Connection conn = getConnection()) {
            int savedId = saveSafeSessionUsingConnection(conn, safeSession)

            if (savedId > 0) {
                return getSafeSessionUsingConnection(conn, savedId)
            }

            throw new SafeSessionUpdateException(safeSession, "Failed to update session as data has been updated by another process. Please try again.")
        }
    }

    private def saveSafeSessionUsingConnection(Connection conn, SafeSession safeSession) {
        try (CallableStatement saveSafeSessionStatement = conn.prepareCall("{ call saveSafeSession(?, ?, ?) }")) {
            if (safeSession.id > 0) {
                saveSafeSessionStatement.setInt(1, safeSession.id)
            } else {
                saveSafeSessionStatement.setNull(1, Types.INTEGER)
            }

            saveSafeSessionStatement.setString(2, gsonProvider.gson.toJson(safeSession, SafeSession.class))
            saveSafeSessionStatement.executeUpdate()

            int sessionId = saveSafeSessionStatement.getInt(3)

            safeSession.setId(sessionId) // Update the safe session object with the new ID

            return sessionId
        } catch (Exception ex) {
            log.error("Error persisting safe session for retailer: ${safeSession.getRetailerId()} store: ${safeSession.getStoreId()} safeId: ${safeSession.getSafeId()} error: ${ex.getMessage()}", ex)
            throw new RuntimeException("Error persisting safe session for retailer: ${safeSession.getRetailerId()} store: ${safeSession.getStoreId()} safeId: ${safeSession.getSafeId()} error: ${ex.getMessage()}", ex)
        }
    }

    SafeSession getActiveSession(int safeId) {
        try (Connection conn = getConnection()) {
            return getActiveSessionUsingConnection(conn, safeId)
        }
    }

    private SafeSession getActiveSessionUsingConnection(Connection conn, int safeId) {
        getActiveSafeSessionsUsingConnection(conn, safeId).stream().findFirst().orElse(null)
    }

    List<SafeSession> getActiveSafeSessions(Integer safeId) {
        try (Connection conn = getConnection()) {
            return getActiveSafeSessionsUsingConnection(conn, safeId)
        }
    }

    private List<SafeSession> getActiveSafeSessionsUsingConnection(Connection conn, Integer safeId) {
        List<SafeSession> safeSessions = new ArrayList<>()
        try (CallableStatement stmt = conn.prepareCall("{ call getActiveSafeSession(?, ?, ?) }")) {
            stmt.setInt(1, springSecurityService.principal.retailerId)
            if (springSecurityService.principal.storeId != null) {
                stmt.setInt(2, springSecurityService.principal.storeId)
            } else {
                stmt.setNull(2, Types.INTEGER)
            }
            if (safeId != null) {
                stmt.setInt(3, safeId)
            } else {
                stmt.setNull(3, Types.INTEGER)
            }
            ResultSet rs = stmt.executeQuery()
            try {
                while (rs.next()) {
                    String sessionJson = rs.getString("session")
                    safeSessions.add(gsonProvider.gson.fromJson(sessionJson, SafeSession.class))
                }
            } finally {
                rs.close()
            }
        } catch (Exception ex) {
            log.error("Error loading active safe session for retailer: ${springSecurityService.principal.retailerId} safeId: ${safeId} error: ${ex.getMessage()}", ex)
            throw new RuntimeException("Error loading active safe session for retailer: ${springSecurityService.principal.retailerId} safeId: ${safeId} error: ${ex.getMessage()}", ex)
        }
        return safeSessions
    }

    def getSafeSession(int safeSessionId) {
        try (Connection conn = getConnection()) {
            return getSafeSessionUsingConnection(conn, safeSessionId)
        }
    }


    def getSafeSessionUsingConnection(Connection conn, int safeSessionId) {
        try (CallableStatement getSafeSessionStatement = conn.prepareCall("{ call getSafeSession(?, ?, ?) }")) {
            getSafeSessionStatement.setInt(1, springSecurityService.principal.retailerId)
            getSafeSessionStatement.setInt(2, springSecurityService.principal.storeId)
            getSafeSessionStatement.setInt(3, safeSessionId)
            ResultSet rs = getSafeSessionStatement.executeQuery()
            try {
                if (rs.next()) {
                    String safeSessionJson = rs.getString("session")
                    return gsonProvider.gson.fromJson(safeSessionJson, SafeSession.class)
                }
            } finally {
                rs.close()
            }
        }catch (Exception ex) {
            log.error("Error loading safe session for from retailer: ${springSecurityService.principal.retailerId} store: ${springSecurityService.principal.storeId} safe SessionId: ${safeSessionId} " + "error: ${ex.getMessage()}", ex)
            throw new RuntimeException("Error loading safe session for from retailer: ${springSecurityService.principal.retailerId} store: ${springSecurityService.principal.storeId} safe SessionId: ${safeSessionId} " + "error: ${ex.getMessage()}", ex)
        }

        return null
    }

